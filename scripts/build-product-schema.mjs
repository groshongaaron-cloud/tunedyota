// Render the Magnuson Product/Offer JSON-LD statically into the supercharger
// pages' <head>, replacing the client-side injection path (magnuson-schema.js)
// as the primary source. Static markup is first-wave crawlable — no rendering
// queue — which matters for Merchant-listing/product-snippet eligibility.
//
// Mirrors site/magnuson-schema.js exactly (same catalog, same shapes); the
// client injector stays in the pages as a dormant fallback — it skips itself
// when a static block is present, and covers any new vehicle page added
// without running this build.
//
// Data source: site/magnuson-catalog.js (window.MAGNUSON_CATALOG).
// Run via `npm run build:seo` (chained) or standalone:
//   node scripts/build-product-schema.mjs
import fs from "node:fs";
import path from "node:path";

const SITE = "site";
const START = "<!-- SEO:PRODUCT:START (generated by scripts/build-product-schema.mjs — do not edit) -->";
const END = "<!-- SEO:PRODUCT:END -->";

// Evaluate the browser catalog file with a window stub.
const catalogSrc = fs.readFileSync(path.join(SITE, "magnuson-catalog.js"), "utf8");
const windowStub = {};
new Function("window", catalogSrc)(windowStub);
const C = windowStub.MAGNUSON_CATALOG;
if (!C) throw new Error("MAGNUSON_CATALOG not found in site/magnuson-catalog.js");

const BUSINESS = {
  "@type": "AutomotiveBusiness",
  "@id": "https://tunedyota.com/#business",
  "name": "Tuned Yota",
  "telephone": "+1-612-406-7117",
  "url": "https://tunedyota.com/",
};

// Keep in lockstep with imageForApp() in site/magnuson-schema.js.
function imageForApp(app) {
  const base = "https://tunedyota.com/images/magnuson/";
  const e = app.engine, v = app.vehicle;
  const names = app.kits.map((k) => k.name).join(" ");
  let f;
  if (/i-FORCE/i.test(e)) f = "tundra-sequoia-34-perfpack.jpg";
  else if (/5\.7L/.test(e)) f = /Tundra/i.test(v) ? "tundra-57-tvs2650.jpg" : "lc-sequoia-lx570-tvs2650.jpg";
  else if (/4\.5L/.test(e)) f = "landcruiser-45-classic.jpg";
  else if (/3\.5L/.test(e)) f = "tacoma-35-tvs1900.jpg";
  else if (/3\.4L/.test(e)) f = "toyota-34-tvs1320.jpg";
  else if (/4\.0L/.test(e)) f = /TVS1320/i.test(names) ? "4runner-fj-40-tvs1320.jpg"
    : (/Tacoma/i.test(v) ? "tacoma-40-mp90.jpg" : "mp90-40-box.jpg");
  return f ? base + f : "https://tunedyota.com/og-image.png";
}

function productFor(app, kit) {
  return {
    "@type": "Product",
    "name": `${kit.name} — ${app.vehicle} ${app.years} (${app.engine})`,
    "sku": kit.sku,
    "mpn": kit.sku,
    "brand": { "@type": "Brand", "name": "Magnuson Superchargers" },
    "category": "Vehicle Superchargers & Parts",
    "image": imageForApp(app),
    "description": `${kit.name} for ${app.years} ${app.vehicle} with the ${app.engine}. Genuine Magnuson hardware sold by Tuned Yota, an authorized Magnuson dealer, installer, servicer and calibrator specializing in Toyota and Lexus. Ships to the lower 48; installation and OTT calibration available in the Upper Midwest.`,
    "offers": {
      "@type": "Offer",
      "url": `https://tunedyota.com/${app.slug}`,
      "price": String(kit.retail),
      "priceCurrency": "USD",
      "priceValidUntil": "2026-12-31",
      "availability": "https://schema.org/InStock",
      "itemCondition": "https://schema.org/NewCondition",
      "seller": BUSINESS,
    },
  };
}

function ldFor(slug) {
  const apps = slug ? C.applications.filter((a) => a.slug === slug) : C.applications;
  const products = [];
  const seen = new Set();
  for (const app of apps) {
    for (const kit of app.kits) {
      const key = `${kit.sku}|${app.slug}`;
      if (seen.has(key)) continue;
      seen.add(key);
      products.push(productFor(app, kit));
    }
  }
  if (!products.length) return null;
  return slug && products.length === 1
    ? { "@context": "https://schema.org", ...products[0] }
    : {
        "@context": "https://schema.org",
        "@type": "ItemList",
        "name": "Magnuson Supercharger Kits for Toyota & Lexus — Tuned Yota",
        "numberOfItems": products.length,
        "itemListElement": products.map((p, i) => ({ "@type": "ListItem", "position": i + 1, "item": p })),
      };
}

// Every page that includes the client injector gets the static block.
const pages = fs.readdirSync(SITE).filter((f) => {
  if (!f.endsWith(".html")) return false;
  return fs.readFileSync(path.join(SITE, f), "utf8").includes("magnuson-schema.js");
});

let done = 0;
for (const f of pages) {
  const p = path.join(SITE, f);
  let html = fs.readFileSync(p, "utf8");
  const slugMatch = html.match(/data-veh-slug="([^"]+)"/);
  const ld = ldFor(slugMatch ? slugMatch[1] : null);
  if (!ld) { console.warn(`${f}: no catalog products — skipped`); continue; }
  const block = `${START}\n<script type="application/ld+json" data-magnuson="static">${JSON.stringify(ld)}</script>\n${END}`;
  if (html.includes(START)) {
    html = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`), block);
  } else {
    html = html.replace("</head>", `${block}\n</head>`);
  }
  fs.writeFileSync(p, html);
  done++;
}
console.log(`product schema: static JSON-LD written into ${done} page(s)`);
