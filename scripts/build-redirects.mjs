// Regenerate the forced .html→clean-URL 301 block in site/_redirects.
//
// Every page serves at two URLs (/foo and /foo.html); canonicals point at /foo
// and (since 2026-07-29) all internal links do too. These forced rules (`301!`
// — required, because Netlify won't redirect a path where a file exists) close
// the loop so the .html twins stop being crawlable duplicates.
//
// The rule set is derived from site/sitemap.xml — exactly the canonical set —
// so app-shell pages that must keep their .html path (installer.html, app.html;
// service-worker cache keys) are never touched: they aren't in the sitemap.
//
// Run via `npm run build:seo` (chained) or standalone:
//   node scripts/build-redirects.mjs
import fs from "node:fs";

const REDIRECTS = "site/_redirects";
const START = "# ── AUTO:HTML-301 START (generated by scripts/build-redirects.mjs — do not edit) ──";
const END = "# ── AUTO:HTML-301 END ──";

const xml = fs.readFileSync("site/sitemap.xml", "utf8");
const paths = [...xml.matchAll(/<loc>https:\/\/tunedyota\.com([^<]*)<\/loc>/g)]
  .map((m) => m[1].trim() || "/");

const rules = paths
  .map((p) => (p === "/" ? "/index.html / 301!" : `${p}.html ${p} 301!`))
  .sort();

const block = `${START}\n${rules.join("\n")}\n${END}`;
let txt = fs.readFileSync(REDIRECTS, "utf8").replace(/\r\n/g, "\n");
if (txt.includes(START)) {
  txt = txt.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`), block);
} else {
  txt = txt.trimEnd() + "\n\n" + block + "\n";
}
fs.writeFileSync(REDIRECTS, txt);
console.log(`_redirects: ${rules.length} forced .html→clean 301 rules regenerated`);
